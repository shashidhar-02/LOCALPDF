import { Document, Packer, Paragraph, TextRun, HeadingLevel } from 'docx';

/**
 * Generates an editable DOCX file from extracted PDF text pages.
 * Clearly marked as best-effort text export.
 */
export async function createDocxFromText(
  title: string,
  pages: { page: number; text: string }[]
): Promise<Uint8Array> {
  const children: Paragraph[] = [];

  // Title header
  children.push(
    new Paragraph({
      text: title || 'Extracted Document Text',
      heading: HeadingLevel.TITLE,
      spacing: { after: 300 },
    })
  );

  children.push(
    new Paragraph({
      children: [
        new TextRun({
          text: 'Notice: This document was generated by LocalPDF via client-side best-effort text export. Text has been extracted directly from the PDF without sending any data to a remote server.',
          italics: true,
          size: 18,
          color: '666666',
        }),
      ],
      spacing: { after: 400 },
    })
  );

  for (const page of pages) {
    children.push(
      new Paragraph({
        text: `Page ${page.page}`,
        heading: HeadingLevel.HEADING_2,
        spacing: { before: 240, after: 120 },
      })
    );

    const paragraphs = page.text.split('\n').filter((p) => p.trim());
    if (paragraphs.length === 0) {
      children.push(
        new Paragraph({
          children: [new TextRun({ text: '[No selectable text detected on this page]', italics: true })],
          spacing: { after: 200 },
        })
      );
    } else {
      for (const p of paragraphs) {
        children.push(
          new Paragraph({
            text: p,
            spacing: { after: 150 },
          })
        );
      }
    }
  }

  const doc = new Document({
    sections: [
      {
        properties: {},
        children,
      },
    ],
  });

  const blob = await Packer.toBlob(doc);
  const arrayBuffer = await blob.arrayBuffer();
  return new Uint8Array(arrayBuffer);
}
